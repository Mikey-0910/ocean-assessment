export function computeArchetype(results: AssessmentResults): string {
  const rule = archetypeRules.find((r) => r.test(results));
  return rule ? rule.name : '平衡探索者';
}

export function generateOverallPortrait(results: AssessmentResults): string {
  const dims = ['O', 'C', 'E', 'A', 'N'] as DimensionCode[];
  const phrases = dims.map((d) => overallPortrait[d][results[d].level]);
  return `你像是一个${phrases[0]}的人。${phrases[2]}；${phrases[3]}。同时你${phrases[1]}，而${phrases[4]}。`;
}

export function computeTotalScore(results: AssessmentResults): string {
  return Object.values(results)
    .reduce((sum, r) => sum + r.total, 0)
    .toFixed(1);
}

