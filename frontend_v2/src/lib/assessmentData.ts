export function computeResults(answers: AnswersMap): AssessmentResults {
  const dimScores: Record<string, number[]> = { O: [], C: [], E: [], A: [], N: [] };

  questions.forEach((q) => {
    const ans = answers[q.id];
    if (!ans) return;
    dimScores[q.dimension].push(ans.score);
  });

  const results = {} as AssessmentResults;

  (['O', 'C', 'E', 'A', 'N'] as DimensionCode[]).forEach((d) => {
    const scores = dimScores[d];
    const total = scores.reduce((a, b) => a + b, 0);
    const avg = scores.length > 0 ? total / scores.length : 2.5;
    const level: Level = avg >= 3.0 ? '高' : avg >= 2.0 ? '中' : '低';

    results[d] = {
      total: parseFloat(total.toFixed(2)),
      avg: parseFloat(avg.toFixed(2)),
      level,
    };
  });

  return results;
}

export function scoreOpenTextLocal(text: string): number {
  if (!text || text.trim().length < 3) return 2.5;

  const intensifyWords = ['甚至', '超额', '必须', '立刻', '绝对', '极度享受', '完全无法忍受', '总是', '一定', '完全', '非常', '极其', '特别', '格外', '毫无疑问'];
  const weakenWords = ['偶尔', '尽量', '看心情', '不得不', '有点', '虽然', '但是', '有时', '看情况', '一半一半', '可能', '大概', '勉强', '被迫', '不得已', '懒得', '不太想', '不情愿', '抗拒', '讨厌', '不喜欢'];
  const mixedWords = ['有时候', '看情况', '一半一半', '视情况而定', '时好时坏', '不一定'];

  let baseScore = 2.5;

  const intensifyCount = intensifyWords.reduce((count, word) => count + (text.includes(word) ? 1 : 0), 0);
  const weakenCount = weakenWords.reduce((count, word) => count + (text.includes(word) ? 1 : 0), 0);
  const mixedCount = mixedWords.reduce((count, word) => count + (text.includes(word) ? 1 : 0), 0);

  if (intensifyCount > weakenCount && mixedCount === 0) {
    baseScore = 3.5;
  } else if (weakenCount > intensifyCount && mixedCount === 0) {
    baseScore = 1.5;
  } else if (mixedCount > 0 || (intensifyCount > 0 && weakenCount > 0)) {
    baseScore = 2.5;
  } else if (intensifyCount > 0) {
    baseScore = 3.5;
  } else if (weakenCount > 0) {
    baseScore = 1.5;
  }

  if (text.trim().length < 5) baseScore = Math.min(baseScore, 2.5);

  return Math.max(1.0, Math.min(4.0, baseScore));
}
